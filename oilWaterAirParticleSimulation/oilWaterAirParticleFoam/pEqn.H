// pEqn.H  (FIXED VERSION)
//
// What changed and why
// ────────────────────
//  * phig now contains BOTH the capillary force and the buoyancy term, exactly
//    as in stock interFoam/interIsoFoam:
//
//        phig = (surfaceTensionForce() - ghf*snGrad(rho))*rAUf*magSf
//
//    Previously only the buoyancy part was here and surface tension was applied
//    solely in UEqn as a reconstructed cell force. That breaks the well-balanced
//    (Francois-type) discretisation: the Laplace pressure jump generated by
//    p_rghEqn can then no longer cancel the capillary force at the same faces,
//    so every interface cell keeps a finite residual force. On a 0.7 mm bubble
//    (Eo = rho*g*d^2/sigma ~ 0.07, i.e. surface-tension dominated) that residual
//    is much larger than buoyancy - which is precisely the "bubble does not
//    rise / freezes after a few mm" symptom.
//  * The final velocity correction now reconstructs (phig - p_rghEqn.flux()),
//    which is consistent with the predictor above.
{
    tmp<volScalarField> trAU(1.0/UEqn.A());
    const volScalarField& rAU = trAU();

    surfaceScalarField rAUf("rAUf", fvc::interpolate(rAU));

    volVectorField HbyA(constrainHbyA(rAU*UEqn.H(), U, p_rgh));

    surfaceScalarField phiHbyA
    (
        "phiHbyA",
        fvc::flux(HbyA)
      + MRF.zeroFilter(fvc::interpolate(rho*rAU)*fvc::ddtCorr(U, phi))
    );

    MRF.makeRelative(phiHbyA);

    if (p_rgh.needReference())
    {
        fvc::makeRelative(phiHbyA, U);
        adjustPhi(phiHbyA, U, p_rgh);
        fvc::makeAbsolute(phiHbyA, U);
    }

    surfaceScalarField phig
    (
        (
            mixture.surfaceTensionForce()
          - ghf*fvc::snGrad(rho)
        )*rAUf*mesh.magSf()
    );

    phiHbyA += phig;

    // Update the pressure BCs to ensure flux consistency
    constrainPressure(p_rgh, U, phiHbyA, rAUf, MRF);

    while (pimple.correctNonOrthogonal())
    {
        fvScalarMatrix p_rghEqn
        (
            fvm::laplacian(rAUf, p_rgh) == fvc::div(phiHbyA)
        );

        p_rghEqn.setReference(pRefCell, getRefCellValue(p_rgh, pRefCell));

        p_rghEqn.solve();

        if (pimple.finalNonOrthogonalIter())
        {
            phi = phiHbyA - p_rghEqn.flux();

            p_rgh.relax();

            U = HbyA + rAU*fvc::reconstruct((phig - p_rghEqn.flux())/rAUf);
            U.correctBoundaryConditions();
            fvOptions.correct(U);
        }
    }

    #include "continuityErrs.H"

    // Correct Uf if the mesh is moving
    fvc::correctUf(Uf, U, phi);

    // Make the fluxes relative to the mesh motion
    fvc::makeRelative(phi, U);

    p == p_rgh + rho*gh;

    if (p_rgh.needReference())
    {
        p += dimensionedScalar
        (
            "p",
            p.dimensions(),
            pRefValue - getRefCellValue(p, pRefCell)
        );
        p_rgh == p - rho*gh;
    }
}
